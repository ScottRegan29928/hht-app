/** Get the date range for a week number in a given year */
export function getWeekDates(weekNumber: number, year: number): WeekDate | undefined {
  return WEEK_CALENDAR.find(w => w.weekNumber === weekNumber && w.year === year);
}

/** Get all week dates for a given year */
export function getWeeksForYear(year: number): WeekDate[] {
  return WEEK_CALENDAR.filter(w => w.year === year).sort((a, b) => a.weekNumber - b.weekNumber);
}

/** Get available years */
export const AVAILABLE_YEARS = [2026, 2027, 2028, 2029, 2030];

/** Format a week date range for display: "Sep 11 – Sep 18, 2026" */
export function formatWeekRange(weekNumber: number, year: number): string {
  const wd = getWeekDates(weekNumber, year);
  if (!wd) return `Week ${weekNumber}`;
  const opts: Intl.DateTimeFormatOptions = { month: "short", day: "numeric" };
  const start = new Date(wd.startDate + "T12:00:00");
  const end = new Date(wd.endDate + "T12:00:00");
  const startStr = start.toLocaleDateString("en-US", opts);
  const endYear = end.getFullYear();
  const endOpts: Intl.DateTimeFormatOptions = endYear !== start.getFullYear()
    ? { month: "short", day: "numeric", year: "numeric" }
    : { month: "short", day: "numeric" };
  const endStr = end.toLocaleDateString("en-US", endOpts);
  return `${startStr} – ${endStr}, ${year}`;
}

/** Get all entries */
export function getAllWeekCalendar(): WeekDate[] {
  return WEEK_CALENDAR;
}

/**
 * Returns the next 52 full weeks from today.
 * Each entry includes the weekNumber plus the dates for its *next upcoming* occurrence.
 * Once the current week's end date has passed, it drops off and a new 52nd week is added.
 */
export function getNext52Weeks(): WeekDate[] {
  const today = new Date();
  today.setHours(12, 0, 0, 0);
  const todayISO = today.toISOString().split("T")[0];

  // Gather all future week entries (startDate >= today) across all years
  const futureWeeks = WEEK_CALENDAR
    .filter((w) => w.endDate >= todayISO) // week hasn't ended yet
    .sort((a, b) => a.startDate.localeCompare(b.startDate));

  // Deduplicate by weekNumber — keep earliest upcoming occurrence
  const seen = new Set<number>();
  const result: WeekDate[] = [];
  for (const w of futureWeeks) {
    if (seen.has(w.weekNumber)) continue;
    seen.add(w.weekNumber);
    result.push(w);
    if (result.length >= 52) break;
  }

  return result;
}
